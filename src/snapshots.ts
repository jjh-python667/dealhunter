import { endInstant } from "./extract";
import type { DealRecord } from "./types";

const FORMAT = "v1";
const FRESH_MS = 20 * 60_000;
const MAX_STALE_MS = 6 * 60 * 60_000;
const EDGE_SECONDS = 60;
const DAY_MS = 86_400_000;
export type SnapshotPage = "home" | "ai" | "cloud";
export type SnapshotLang = "zh" | "en";
type Snapshot = { generated_at: number; valid_until: number; html_gzip: ArrayBuffer | number[] };
type EdgeCache = Pick<Cache, "match" | "put">;

function keyFor(page: SnapshotPage, lang: SnapshotLang): string {
  return `${FORMAT}:${page}:${lang}`;
}

// Cut off snapshots before time-dependent UI changes, even during an outage.
export function snapshotBoundary(deals: DealRecord[], now: number): number {
  const shanghaiOffset = 8 * 60 * 60_000;
  let boundary = Math.min(
    now + MAX_STALE_MS,
    (Math.floor(now / DAY_MS) + 1) * DAY_MS,
    (Math.floor((now + shanghaiOffset) / DAY_MS) + 1) * DAY_MS - shanghaiOffset,
  );
  for (const deal of deals) {
    if (deal.status === "archived") continue;
    const start = deal.startsAt ? Date.parse(deal.startsAt) : NaN;
    const end = deal.endsAt ? endInstant(deal.endsAt)?.getTime() : undefined;
    if (start > now) boundary = Math.min(boundary, start);
    if (end !== undefined && end >= now) boundary = Math.min(boundary, end + 1);
  }
  return boundary;
}

export async function saveSnapshots(
  db: D1Database,
  generatedAt: number,
  validUntil: number,
  pages: Array<{page: SnapshotPage; lang: SnapshotLang; html: string}>,
): Promise<void> {
  const writes = [];
  for (const {page, lang, html} of pages) {
    const compressed = await new Response(new Response(html).body!.pipeThrough(new CompressionStream("gzip"))).arrayBuffer();
    writes.push(db.prepare(`INSERT INTO portal_snapshots (snapshot_key, generated_at, valid_until, html_gzip)
      VALUES (?, ?, ?, ?) ON CONFLICT(snapshot_key) DO UPDATE SET generated_at = excluded.generated_at,
      valid_until = excluded.valid_until, html_gzip = excluded.html_gzip
      WHERE excluded.generated_at > portal_snapshots.generated_at`)
      .bind(keyFor(page, lang), generatedAt, validUntil, compressed));
  }
  await db.batch(writes);
}

function cacheResult(response: Response, outcome: string, rows?: number): Response {
  const headers = new Headers(response.headers);
  headers.set("cache-control", "no-store");
  headers.set("x-dealhunter-cache", outcome);
  if (rows !== undefined) headers.append("server-timing", `snapshot_d1_rows;dur=${rows}`);
  return new Response(response.body, { status: response.status, headers });
}

export async function serveSnapshot(options: {
  request: Request;
  page: SnapshotPage;
  lang: SnapshotLang;
  db: D1Database;
  cache?: EdgeCache;
  defer?: (promise: Promise<void>) => void;
  live: () => Promise<Response>;
  html: (body: string) => Response;
  now?: number;
}): Promise<Response> {
  const {request, page, lang, db, cache, live, html} = options;
  const now = options.now ?? Date.now();
  if (request.method !== "GET" || request.headers.has("authorization") || request.headers.has("cf-access-jwt-assertion")) {
    return cacheResult(await live(), "BYPASS");
  }
  const key = new Request(new URL(`/_dealhunter_snapshot/${keyFor(page, lang)}`, request.url));
  try {
    const edge = await cache?.match(key);
    if (edge && Number(edge.headers.get("x-snapshot-fresh-until")) > now) return cacheResult(edge, "EDGE", 0);
  } catch {
    // The cache is an optimization. The stored snapshot remains available.
  }
  let snapshot: Snapshot | undefined;
  let rows: number | undefined;
  try {
    const result = await db.prepare(`SELECT generated_at, valid_until, html_gzip FROM portal_snapshots WHERE snapshot_key = ?`)
      .bind(keyFor(page, lang)).all<Snapshot>();
    snapshot = result.results[0];
    rows = result.meta.rows_read;
  } catch {
    // During rollout, the live path also works before the migration is applied.
  }
  if (snapshot && snapshot.valid_until > now) {
    const freshUntil = Math.min(snapshot.valid_until, snapshot.generated_at + FRESH_MS);
    let rendered: Response | undefined;
    try {
      const bytes = new Uint8Array(snapshot.html_gzip);
      const body = await new Response(new Response(bytes).body!.pipeThrough(new DecompressionStream("gzip"))).text();
      rendered = html(body);
      rendered.headers.set("x-snapshot-generated-at", new Date(snapshot.generated_at).toISOString());
      rendered.headers.set("x-snapshot-fresh-until", String(freshUntil));
    } catch {
      // A corrupt snapshot can be regenerated by the next successful collection.
    }
    if (rendered && freshUntil > now) {
      const ttl = Math.min(EDGE_SECONDS, Math.floor((freshUntil - now) / 1000));
      if (cache && ttl > 0) {
        const copy = rendered.clone();
        copy.headers.set("cache-control", `public, max-age=${ttl}`);
        const write = cache.put(key, copy).catch(() => undefined);
        if (options.defer) options.defer(write);
        else await write;
      }
      return cacheResult(rendered, "SNAPSHOT", rows);
    }
    const current = await live();
    if (rendered && current.status >= 500) return cacheResult(rendered, "STALE", rows);
    return cacheResult(current, "LIVE", rows);
  }
  return cacheResult(await live(), "LIVE", rows);
}
